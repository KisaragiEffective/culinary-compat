package io.github.smokahs.culinarycompat.foodnerf;

import java.io.InputStream;
import java.io.InputStreamReader;

import net.minecraft.core.component.DataComponents;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.food.FoodProperties;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.neoforged.neoforge.event.ModifyDefaultComponentsEvent;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import io.github.smokahs.culinarycompat.CulinaryCompat;
import io.github.smokahs.culinarycompat.config.Configs;

public final class FoodNerf {
	private FoodNerf() {
	}

	public static void modifyComponents(ModifyDefaultComponentsEvent event) {
		JsonArray itemsToChange = new JsonArray();

		if (Configs.Common.nerfPams) {
			appendItems(itemsToChange, "food-data/autogenerated.json");
			appendItems(itemsToChange, "food-data/manual.json");
		}
		if (Configs.Common.nerfCroptopia) {
			appendItems(itemsToChange, "food-data/croptopianerf.json");
		}
		if (Configs.Common.nerfMinecraft) {
			appendItems(itemsToChange, "food-data/minecraftnerf.json");
		}
		if (Configs.Common.inedibleIngredients) {
			appendItems(itemsToChange, "food-data/inedibleingredients.json");
		}
		if (itemsToChange.isEmpty())
			return;

		for (JsonElement element : itemsToChange) {
			JsonObject obj = element.getAsJsonObject();
			String id = obj.get("id").getAsString();
			int hunger = obj.get("hunger").getAsInt();
			float saturation = obj.get("saturation").getAsFloat();

			ResourceLocation rl = ResourceLocation.tryParse(id);
			if (rl == null)
				continue;
			Item item = BuiltInRegistries.ITEM.get(rl);
			if (item == null || item == net.minecraft.world.item.Items.AIR)
				continue;

			if (hunger == 0 && saturation == 0.0f) {
				event.modify(item, builder -> builder.remove(DataComponents.FOOD));
				continue;
			}

			FoodProperties oldProps = new ItemStack(item).getFoodProperties(null);
			FoodProperties replacement = oldProps == null
					? new FoodProperties.Builder().nutrition(hunger).saturationModifier(saturation).build()
					: new FoodProperties(hunger, hunger * saturation * 2.0f, oldProps.canAlwaysEat(),
							oldProps.eatSeconds(), oldProps.usingConvertsTo(), oldProps.effects());
			event.modify(item, builder -> builder.set(DataComponents.FOOD, replacement));
		}
	}

	private static void appendItems(JsonArray target, String path) {
		JsonElement loaded = loadFile(path);
		if (loaded == null || !loaded.isJsonObject())
			return;
		JsonArray arr = loaded.getAsJsonObject().getAsJsonArray("items");
		if (arr == null)
			return;
		for (JsonElement e : arr)
			target.add(e);
	}

	private static JsonElement loadFile(String fileName) {
		try (InputStream stream = FoodNerf.class.getClassLoader().getResourceAsStream(fileName)) {
			if (stream == null) {
				CulinaryCompat.LOGGER.error("food nerf data missing: {}", fileName);
				return null;
			}
			return JsonParser.parseReader(new InputStreamReader(stream));
		} catch (Exception e) {
			CulinaryCompat.LOGGER.error("food nerf data failed to load: {}", fileName, e);
			return null;
		}
	}

}
